//! C0595: `evaluation.rubric_based_tool_use_quality_v1`, ported from
//! `google.adk.evaluation.rubric_based_tool_use_quality_v1`.
//!
//! [`RubricBasedToolUseV1Evaluator`] composes a
//! [`crate::rubric_based_evaluator::RubricBasedEvaluator`] (C0601) rather
//! than subclassing it — same reasoning as `rubric_based_evaluator.rs`
//! itself composing [`crate::llm_as_judge::LlmAsJudgeConfig`] instead of
//! extending a trait: `RubricBasedEvaluator` isn't a Rust trait, just a
//! struct with the three source-implemented hooks, so this wraps one and
//! supplies only `format_auto_rater_prompt` and an `evaluate_invocations`
//! entry point that drives [`crate::llm_as_judge::evaluate_invocations_via_llm_judge`]
//! with all four hooks.
//!
//! **Does not implement [`crate::evaluator::Evaluator`], disclosed**: same
//! reason `llm_as_judge.rs`'s harness itself doesn't — the harness is
//! inherently async (it awaits a judge-model call), and `Evaluator::evaluate_invocations`
//! is deliberately sync so as not to break its three already-shipped
//! implementors. This evaluator is a real, callable, tested type, just
//! not one the sync-only [`crate::metric_evaluator_registry::MetricEvaluatorRegistry`]
//! can hold — the same disclosed gap the registry's own module doc
//! already names (it lists this evaluator as blocked; see this crate's
//! `CHANGELOG.md`/manifest for the correction that it's now built, just
//! still unregistrable for this same structural reason).

use crate::eval_case::Invocation;
