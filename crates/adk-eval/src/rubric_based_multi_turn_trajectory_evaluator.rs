//! C0598: `evaluation.rubric_based_multi_turn_trajectory_evaluator`,
//! ported from
//! `google.adk.evaluation.rubric_based_multi_turn_trajectory_evaluator`.
//!
//! Same composition-over-subclassing shape as
//! `rubric_based_tool_use_quality_v1.rs` (see that module's doc) — wraps a
//! [`crate::rubric_based_evaluator::RubricBasedEvaluator`]. Unlike the
//! other three rubric-based metrics in this batch, the source overrides
//! `evaluate_invocations` itself (not just `format_auto_rater_prompt`):
//! it accumulates the full multi-turn dialogue, marks every turn but the
//! last `NOT_EVALUATED`, and runs a single judge call on the last turn
//! with the accumulated context. Ported as
//! [`RubricBasedMultiTurnTrajectoryEvaluator::evaluate_invocations`],
//! which drives [`crate::llm_as_judge::evaluate_invocations_via_llm_judge`]
//! on a one-element slice (just the last invocation) rather than the full
//! list the other three metrics pass through unchanged.
//!
//! **Dialogue assembly, disclosed narrowing on `tool_declarations`**: the
//! source's `_assemble_dialogue_history` reaches into each declared tool's
//! `function_declarations` (a `genai_types.Tool`'s nested list) to list
//! tool names/descriptions. [`crate::app_details::AgentDetails::tool_declarations`]
//! is an opaque `Vec<Value>` in this port (that narrowing already
//! disclosed on `AgentDetails` itself, and — since nothing in this port
//! populates it yet — untested against real data either way), so this is
//! read defensively via [`rusty_serde::value::Value::get`]/`as_str`
//! rather than a typed field access, tolerating a missing or
//! differently-shaped entry by simply skipping it.
//!
//! **`dict.fromkeys(...)` dedup-preserving-order, disclosed narrowing**:
//! the source dedupes `instructions_parts`/`tools_parts` while preserving
//! first-seen order via `dict.fromkeys`. This port's equivalent tracks a
//! `HashSet` of already-seen strings alongside a `Vec` to preserve
//! insertion order exactly (unlike the `HashMap`-grouping narrowing used
//! elsewhere in this crate) — order matters here since it's rendered
//! directly into the judge prompt.

