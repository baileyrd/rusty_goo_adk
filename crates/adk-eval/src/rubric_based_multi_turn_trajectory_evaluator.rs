/// The three locally-assembled prompt fragments `_assemble_dialogue_history`
/// computes from the full invocation list, ahead of formatting the actual
/// prompt on just the last turn.
struct DialogueContext {
    formatted_dialogue: String,
    formatted_instructions: String,
    formatted_tools: String,
}

/// Pushes `value` onto `into` only the first time it's seen — the
/// order-preserving `dict.fromkeys(...)` equivalent. See this module's
/// doc.
fn push_deduped(into: &mut Vec<String>, seen: &mut HashSet<String>, value: String) {
    if seen.insert(value.clone()) {
        into.push(value);
    }
}

/// `RubricBasedMultiTurnTrajectoryEvaluator._assemble_dialogue_history`.
fn assemble_dialogue_history(actual_invocations: &[Invocation]) -> DialogueContext {
    let mut dialogue_lines: Vec<String> = Vec::new();

    for (index, invocation) in actual_invocations.iter().enumerate() {
        let turn_number = index + 1;

        // USER TURN.
        let user_text_parts: Vec<&str> = invocation
            .user_content
            .parts
            .iter()
            .filter_map(|p| p.text.as_deref())
            .filter(|t| !t.is_empty())
            .collect();
        if !user_text_parts.is_empty() {
            dialogue_lines.push(format!(
                "USER TURN {turn_number}: {}",
                user_text_parts.join(" ")
            ));
        }

        // INTERMEDIATE TOOL EVENTS.
        if let Some(IntermediateDataType::Events(events)) = invocation.intermediate_data_type() {
            for event in &events.invocation_events {
                let role = if event.author.eq_ignore_ascii_case("user") {
                    "USER".to_string()
                } else {
                    format!("AGENT ({})", event.author)
                };
                if let Some(content) = &event.content {
                    let text_parts: Vec<&str> = content
                        .parts
                        .iter()
                        .filter_map(|p| p.text.as_deref())
                        .filter(|t| !t.is_empty())
                        .collect();
                    if !text_parts.is_empty() {
                        dialogue_lines.push(format!(
                            "{role} TURN {turn_number}: {}",
                            text_parts.join(" ")
                        ));
                    }
                    for part in &content.parts {
                        if let Some(function_call) = &part.function_call {
                            let args = function_call
                                .args
                                .as_ref()
                                .map(|args| {
                                    rusty_serde::json::to_string(args)
                                        .unwrap_or_else(|_| "{}".to_string())
                                })
                                .unwrap_or_else(|| "{}".to_string());
                            dialogue_lines.push(format!(
                                "{role} TURN {turn_number} (tool call): {}({args})",
                                function_call.name.as_deref().unwrap_or("")
                            ));
                        }
                        if let Some(function_response) = &part.function_response {
                            let response = function_response
                                .response
                                .as_ref()
                                .map(|response| {
                                    rusty_serde::json::to_string(response)
                                        .unwrap_or_else(|_| "{}".to_string())
                                })
                                .unwrap_or_else(|| "{}".to_string());
                            dialogue_lines.push(format!(
                                "{role} TURN {turn_number} (tool output): {} -> {response}",
                                function_response.name.as_deref().unwrap_or("")
                            ));
                        }
                    }
                }
            }
        }

        // FINAL AGENT TURN.
        if let Some(final_response) = &invocation.final_response {
            let text_parts: Vec<&str> = final_response
                .parts
                .iter()
                .filter_map(|p| p.text.as_deref())
                .filter(|t| !t.is_empty())
                .collect();
            if !text_parts.is_empty() {
                let agent_name = match invocation.intermediate_data_type() {
                    Some(IntermediateDataType::Events(events))
                        if !events.invocation_events.is_empty() =>
                    {
                        events.invocation_events[0].author.clone()
                    }
                    _ => "agent".to_string(),
                };
                dialogue_lines.push(format!(
                    "AGENT ({agent_name}) TURN {turn_number}: {}",
                    text_parts.join(" ")
                ));
            }
        }
    }

    let mut instructions_parts = Vec::new();
    let mut instructions_seen = HashSet::new();
    let mut tools_parts = Vec::new();
    let mut tools_seen = HashSet::new();
    for invocation in actual_invocations {
        let Some(app_details) = &invocation.app_details else {
            continue;
        };
        for (agent_id, details) in &app_details.agent_details {
            push_deduped(
                &mut instructions_parts,
                &mut instructions_seen,
                format!("Agent {agent_id} Instructions:\n{}", details.instructions),
            );
            push_deduped(
                &mut tools_parts,
                &mut tools_seen,
                format!("Agent: {agent_id}"),
            );
            for tool in &details.tool_declarations {
                let Some(function_declarations) =
                    tool.get("functionDeclarations").and_then(|v| v.as_seq())
                else {
                    continue;
                };
                for func in function_declarations {
                    let name = func.get("name").and_then(|v| v.as_str()).unwrap_or("");
                    let description = func
                        .get("description")
                        .and_then(|v| v.as_str())
                        .unwrap_or("");
                    push_deduped(
                        &mut tools_parts,
                        &mut tools_seen,
                        format!("- {name}: {description}"),
                    );
                }
            }
        }
    }

    DialogueContext {
        formatted_dialogue: dialogue_lines.join("\n"),
        formatted_instructions: instructions_parts.join("\n\n"),
        formatted_tools: tools_parts.join("\n"),
    }
}

/// `rubric_based_multi_turn_trajectory_evaluator.RubricBasedMultiTurnTrajectoryEvaluator`.
pub struct RubricBasedMultiTurnTrajectoryEvaluator {
    evaluator: RubricBasedEvaluator,
}

impl RubricBasedMultiTurnTrajectoryEvaluator {
    pub fn new(eval_metric: &EvalMetric) -> Result<Self, LlmAsJudgeError> {
        Ok(Self {
            evaluator: RubricBasedEvaluator::new(eval_metric, Some(RUBRIC_TYPE.to_string()))?,
        })
    }

    /// `RubricBasedMultiTurnTrajectoryEvaluator.format_auto_rater_prompt`
    /// — formats the prompt using the already-assembled dialogue context
    /// plus the rubrics carried on `actual_invocation` (always the single
    /// last turn — see [`Self::evaluate_invocations`]).
    fn format_auto_rater_prompt(
        &self,
        actual_invocation: &Invocation,
        context: &DialogueContext,
    ) -> String {
        self.evaluator
            .create_effective_rubrics_list(actual_invocation.rubrics.as_deref())
            .expect("rubrics are required for this metric");

        let rubrics_json: Vec<rusty_serde::value::Value> = self
            .evaluator
            .get_effective_rubrics_list()
            .expect("create_effective_rubrics_list() was just called")
            .iter()
            .map(|r| {
                let mut object = rusty_serde::value::Value::Map(Vec::new());
                object.insert("id", rusty_serde::value::Value::String(r.rubric_id.clone()));
                object.insert(
                    "property",
                    match &r.rubric_content.text_property {
                        Some(text) => rusty_serde::value::Value::String(text.clone()),
                        None => rusty_serde::value::Value::Null,
                    },
                );
                if let Some(rubric_type) = &r.rubric_type {
                    object.insert(
                        "type",
                        rusty_serde::value::Value::String(rubric_type.clone()),
                    );
                }
                object
            })
            .collect();
        let formatted_rubrics =
            rusty_serde::json::to_string(&rusty_serde::value::Value::Seq(rubrics_json))
                .unwrap_or_default();

        AUTO_RATER_PROMPT_TEMPLATE
            .replacen("{user_agent_dialogue}", &context.formatted_dialogue, 1)
            .replacen("{properties}", &formatted_rubrics, 1)
            .replacen("{agent_instructions}", &context.formatted_instructions, 1)
            .replacen("{agent_tool_definitions}", &context.formatted_tools, 1)
    }

    /// `RubricBasedMultiTurnTrajectoryEvaluator.evaluate_invocations` — not
    /// [`crate::evaluator::Evaluator::evaluate_invocations`] (same
    /// disclosed reason as every other evaluator in this batch), and
    /// unlike them, not a thin pass-through to
    /// [`evaluate_invocations_via_llm_judge`] over the full invocation
    /// list either: the first N-1 turns are marked `NotEvaluated` locally,
    /// and the harness runs once on just the last turn with the
    /// accumulated dialogue context.
    pub async fn evaluate_invocations(
        &self,
        actual_invocations: &[Invocation],
        expected_invocations: Option<&[Invocation]>,
    ) -> Result<EvaluationResult, LlmAsJudgeError> {
        validate_invocation_lengths(actual_invocations, expected_invocations)
            .map_err(LlmAsJudgeError::InvalidInvocations)?;
        if actual_invocations.is_empty() {
            return Ok(EvaluationResult::default());
        }

        let context = assemble_dialogue_history(actual_invocations);

        let expected_by_invocation: Vec<Option<&Invocation>> = match expected_invocations {
            Some(expected) => expected.iter().map(Some).collect(),
            None => vec![None; actual_invocations.len()],
        };

        let mut per_invocation_results = Vec::new();
        for (actual, expected) in actual_invocations[..actual_invocations.len() - 1]
            .iter()
            .zip(&expected_by_invocation[..expected_by_invocation.len() - 1])
        {
            per_invocation_results.push(PerInvocationResult {
                actual_invocation: actual.clone(),
                expected_invocation: expected.cloned(),
                score: None,
                eval_status: EvalStatus::NotEvaluated,
                rubric_scores: None,
            });
        }

        let last_actual = std::slice::from_ref(&actual_invocations[actual_invocations.len() - 1]);
        let last_expected_invocation = expected_by_invocation[expected_by_invocation.len() - 1];
        let last_expected_owned = last_expected_invocation.cloned();
        let last_expected_slice = last_expected_owned.as_ref().map(std::slice::from_ref);

        let last_turn_result = evaluate_invocations_via_llm_judge(
            self.evaluator.config.judge_model.as_ref(),
            &self.evaluator.config.criterion.judge_model_options,
            self.evaluator.config.threshold,
            false,
            last_actual,
            last_expected_slice,
            |actual, _expected| self.format_auto_rater_prompt(actual, &context),
            |response| {
                self.evaluator
                    .convert_auto_rater_response_to_score(response)
            },
            |samples| self.evaluator.aggregate_per_invocation_samples(samples),
            |results| self.evaluator.aggregate_invocation_results(results),
        )
        .await?;

        per_invocation_results.extend(last_turn_result.per_invocation_results.clone());

        Ok(EvaluationResult {
            overall_score: last_turn_result.overall_score,
            overall_eval_status: last_turn_result.overall_eval_status,
            per_invocation_results,
            overall_rubric_scores: last_turn_result.overall_rubric_scores,
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::app_details::{AgentDetails, AppDetails};
    use crate::eval_case::{InvocationEvent, InvocationEvents};
    use crate::eval_metrics::JudgeModelOptions;
    use crate::eval_rubrics::{Rubric, RubricContent};
    use adk_genai::content::{Content, FunctionCall, Part};
    use adk_models::base_llm::{BaseLlm, BaseLlmError};
    use adk_models::llm_response::LlmResponse;
    use std::future::Future;
    use std::pin::Pin;
    use std::sync::Mutex;

    fn rubric(id: &str, text: &str) -> Rubric {
        Rubric {
            rubric_id: id.to_string(),
            rubric_content: RubricContent {
                text_property: Some(text.to_string()),
            },
            description: None,
            rubric_type: None,
        }
    }

    fn eval_metric_with_rubrics(rubrics: Vec<Rubric>) -> EvalMetric {
        let criterion = crate::eval_metrics::RubricsBasedCriterion {
            threshold: 0.5,
            include_intermediate_responses_in_final: false,
            judge_model_options: JudgeModelOptions {
                judge_model: "gemini-2.5-flash".to_string(),
                num_samples: 1,
                ..Default::default()
            },
            rubrics,
        };
        let value = rusty_serde::json::to_value(&criterion).unwrap();
        EvalMetric::new("rubric_based_multi_turn_trajectory_quality_v1").with_criterion(value)
    }

    fn turn(user_text: &str, tool_name: &str, final_text: &str) -> Invocation {
        Invocation {
            invocation_id: "inv".to_string(),
            user_content: Content::user_text(user_text),
            final_response: Some(Content::new("model", vec![Part::text(final_text)])),
            intermediate_data: Some(
                rusty_serde::json::to_value(&InvocationEvents {
                    invocation_events: vec![InvocationEvent {
                        author: "flight_agent".to_string(),
                        content: Some(Content {
                            role: None,
                            parts: vec![Part {
                                function_call: Some(FunctionCall {
                                    id: Some("c1".to_string()),
                                    name: Some(tool_name.to_string()),
                                    args: None,
                                    ..Default::default()
                                }),
                                ..Default::default()
                            }],
                        }),
                        grounding_metadata: None,
                    }],
                })
                .unwrap(),
            ),
            creation_timestamp: 0.0,
            rubrics: None,
            app_details: Some(AppDetails {
                agent_details: [(
                    "flight_agent".to_string(),
                    AgentDetails::new("flight_agent"),
                )]
                .into_iter()
                .collect(),
            }),
        }
    }

    #[test]
    fn assemble_dialogue_history_numbers_turns_and_includes_tool_calls() {
        let invocations = vec![
            turn("book a flight", "search_flights", "found one"),
            turn("book it", "confirm_booking", "booked"),
        ];
        let context = assemble_dialogue_history(&invocations);
        assert!(context
            .formatted_dialogue
            .contains("USER TURN 1: book a flight"));
        assert!(context
            .formatted_dialogue
            .contains("AGENT (flight_agent) TURN 1 (tool call): search_flights({})"));
        assert!(context
            .formatted_dialogue
            .contains("AGENT (flight_agent) TURN 1: found one"));
        assert!(context.formatted_dialogue.contains("USER TURN 2: book it"));
        assert!(context
            .formatted_dialogue
            .contains("AGENT (flight_agent) TURN 2 (tool call): confirm_booking({})"));
    }

    #[test]
    fn assemble_dialogue_history_dedupes_instructions_preserving_first_seen_order() {
        let invocations = vec![turn("a", "t1", "r1"), turn("b", "t2", "r2")];
        let context = assemble_dialogue_history(&invocations);
        // Only one "Agent flight_agent Instructions:" block despite two turns.
        assert_eq!(
            context
                .formatted_instructions
                .matches("Agent flight_agent Instructions:")
                .count(),
            1
        );
    }

    struct QueueLlm {
        model: String,
        queue: Mutex<Vec<LlmResponse>>,
    }

    impl BaseLlm for QueueLlm {
        fn model(&self) -> &str {
            &self.model
        }
        fn type_name(&self) -> &'static str {
            "QueueLlm"
        }
        fn generate_content_async<'a>(
            &'a self,
            _llm_request: &'a adk_models::llm_request::LlmRequest,
            _stream: bool,
        ) -> Pin<Box<dyn Future<Output = Result<Vec<LlmResponse>, BaseLlmError>> + Send + 'a>>
        {
            let next = self.queue.lock().unwrap().pop();
            Box::pin(async move { Ok(next.into_iter().collect()) })
        }
    }

    fn text_response(text: &str) -> LlmResponse {
        LlmResponse {
            content: Some(Content::new("user", vec![Part::text(text)])),
            ..Default::default()
        }
    }

    #[rusty_tokio::test]
    async fn evaluate_invocations_marks_all_but_the_last_turn_not_evaluated() {
        let eval_metric =
            eval_metric_with_rubrics(vec![rubric("r1", "Confirms the booking with the user.")]);
        let mut evaluator = RubricBasedMultiTurnTrajectoryEvaluator::new(&eval_metric).unwrap();
        evaluator.evaluator.config.judge_model = Box::new(QueueLlm {
            model: "test-model".to_string(),
            queue: Mutex::new(vec![text_response(
                "ID: r1\nProperty: Confirms the booking with the user.\nRationale: It \
                 did.\nVerdict: Yes",
            )]),
        });
        let actual = vec![
            turn("book a flight", "search_flights", "found one"),
            turn("book it", "confirm_booking", "booked"),
        ];
        let result = evaluator.evaluate_invocations(&actual, None).await.unwrap();
        assert_eq!(result.per_invocation_results.len(), 2);
        assert_eq!(
            result.per_invocation_results[0].eval_status,
            EvalStatus::NotEvaluated
        );
        assert_eq!(result.per_invocation_results[0].score, None);
        assert_eq!(
            result.per_invocation_results[1].eval_status,
            EvalStatus::Passed
        );
        assert_eq!(result.overall_eval_status, EvalStatus::Passed);
    }

    #[rusty_tokio::test]
    async fn evaluate_invocations_returns_default_for_no_invocations() {
        let eval_metric = eval_metric_with_rubrics(vec![rubric("r1", "anything")]);
        let evaluator = RubricBasedMultiTurnTrajectoryEvaluator::new(&eval_metric).unwrap();
        let result = evaluator.evaluate_invocations(&[], None).await.unwrap();
        assert_eq!(result, EvaluationResult::default());
    }
}
