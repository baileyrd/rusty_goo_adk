//! C0593: `evaluation.rubric_based_final_response_quality_v1`, ported
//! from `google.adk.evaluation.rubric_based_final_response_quality_v1`.
//!
//! Same composition-over-subclassing shape as
//! `rubric_based_tool_use_quality_v1.rs` (see that module's doc) — wraps a
//! [`crate::rubric_based_evaluator::RubricBasedEvaluator`] and supplies
//! `format_auto_rater_prompt` plus an `evaluate_invocations` entry point.
//! Also does not implement [`crate::evaluator::Evaluator`], for the same
//! disclosed reason.
//!
//! **Agent-name resolution, disclosed narrowing**: the source picks the
//! "current" agent's name from `intermediate_data.invocation_events[0].author`
//! when available, else `next(iter(app_details.agent_details))` — an
//! arbitrary-but-deterministic *first* entry of Python's insertion-ordered
//! dict. [`crate::app_details::AppDetails::agent_details`] is a `HashMap`
//! (already an established narrowing on that type, not one this module
//! introduces), so the fallback here picks an arbitrary-and-not
//! necessarily-deterministic entry instead — only reached when no
//! intermediate events exist, matching the source's own "even when the
//! agent makes zero tool calls" comment about how rarely this fallback is
//! exercised.

use crate::app_details::AppDetails;
use crate::eval_case::{IntermediateDataType, Invocation};
